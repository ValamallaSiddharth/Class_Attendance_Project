import { useEffect, useState } from "react";

function AttendanceReports() {
  const [reports, setReports] = useState([]);
  const [loading, setLoading] = useState(true);

  const loadReports = async () => {
    try {
      setLoading(true);

      const response = await fetch("/api/reports");

      if (!response.ok) {
        setReports([]);
        return;
      }

      const data = await response.json();
      setReports(Array.isArray(data) ? data : []);
    } catch (error) {
      console.error("Failed to load reports:", error);
      setReports([]);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadReports();
  }, []);

  const getBadgeClass = (type) => {
    const fileType = String(type || "").toLowerCase();

    if (fileType === "csv") return "csv";
    if (fileType === "xlsx") return "xlsx";
    if (fileType === "pdf") return "pdf";
    if (fileType === "html") return "html";

    return "default";
  };

  return (
    <div className="page">
      <div className="page-header">
        <div>
          <p className="page-kicker">ATTENDANCE OUTPUTS</p>
          <h1>Attendance Reports</h1>
          <p>
            View, open, and download attendance reports generated by the Smart
            Attendance system.
          </p>
        </div>

        <button className="primary-button" onClick={loadReports}>
          Refresh Reports
        </button>
      </div>

      <div className="info-grid">
        <div className="info-card">
          <span>📄</span>
          <div>
            <h3>{reports.length}</h3>
            <p>Total Reports</p>
          </div>
        </div>

        <div className="info-card">
          <span>📊</span>
          <div>
            <h3>
              {
                reports.filter(
                  (report) => String(report.type).toLowerCase() === "csv"
                ).length
              }
            </h3>
            <p>CSV Files</p>
          </div>
        </div>

        <div className="info-card">
          <span>📘</span>
          <div>
            <h3>
              {
                reports.filter(
                  (report) => String(report.type).toLowerCase() === "xlsx"
                ).length
              }
            </h3>
            <p>Excel Files</p>
          </div>
        </div>
      </div>

      <div className="content-card">
        <div className="section-title-row">
          <div>
            <h2>Generated Files</h2>
            <p>Files are loaded from the project exports folder.</p>
          </div>
        </div>

        {loading ? (
          <div className="empty-state">
            <div className="empty-icon">⏳</div>
            <h3>Loading reports...</h3>
            <p>Please wait while the system checks generated reports.</p>
          </div>
        ) : reports.length === 0 ? (
          <div className="empty-state">
            <div className="empty-icon">📄</div>
            <h3>No reports found yet</h3>
            <p>
              Process attendance from Timetable Control. Generated CSV/XLSX
              files will appear here.
            </p>
          </div>
        ) : (
          <div className="reports-table-wrap">
            <table className="premium-table">
              <thead>
                <tr>
                  <th>File Name</th>
                  <th>Type</th>
                  <th>Size</th>
                  <th>Actions</th>
                </tr>
              </thead>

              <tbody>
                {reports.map((report, index) => (
                  <tr key={report.name || index}>
                    <td>
                      <strong>{report.name}</strong>
                    </td>

                    <td>
                      <span className={`file-badge ${getBadgeClass(report.type)}`}>
                        {report.type || "file"}
                      </span>
                    </td>

                    <td>{report.size_kb ?? "-"} KB</td>

                    <td>
                      <div className="table-actions">
                        <a
                          href={report.download_url || `/api/download/${report.name}`}
                          className="small-button"
                          target="_blank"
                          rel="noreferrer"
                        >
                          Download
                        </a>

                        <a
                          href={report.download_url || `/api/download/${report.name}`}
                          className="small-button ghost"
                          target="_blank"
                          rel="noreferrer"
                        >
                          Open
                        </a>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}

export default AttendanceReports;